"""System and user prompts.

Three channels are kept strictly separate and are labelled as such to the
model:

``SYSTEM INSTRUCTIONS``
    the only source of behaviour;
``USER INPUT``
    the request — data, not instructions about how to behave;
``RETRIEVED REGULATORY CONTEXT``
    quoted regulatory text — **data only**.  Regulatory documents contain
    imperative language ("необходимо представить…", "запрещается…") and could in
    principle contain injected instructions; the prompt states explicitly that
    nothing inside the delimiters may change the system's behaviour.
"""

